#import "SZHeaderWriter.h"

@implementation SZHeaderWriter

+ (NSString *)headerForClass:(SZClassInfo *)info {
    NSMutableString *out = [NSMutableString string];
    NSString *image = info.imagePath.lastPathComponent ?: @"(no image)";
    [out appendFormat:@"// Generated by Swizzlescope for %@ (%@)\n\n", info.name, image];
    [out appendFormat:@"@interface %@", info.name];
    if (info.superclassName) [out appendFormat:@" : %@", info.superclassName];
    if (info.protocolNames.count) [out appendFormat:@" <%@>", [info.protocolNames componentsJoinedByString:@", "]];
    [out appendString:@"\n"];

    if (info.ivars.count) {
        [out appendString:@"{\n"];
        for (SZIvarInfo *ivar in info.ivars) {
            [out appendFormat:@"    %@\t// @%ld\n", ivar.declaration, (long)ivar.offset];
        }
        [out appendString:@"}\n"];
    }
    [out appendString:@"\n"];

    if (info.properties.count) {
        for (SZPropertyInfo *prop in info.properties) [out appendFormat:@"%@\n", prop.declaration];
        [out appendString:@"\n"];
    }
    if (info.classMethods.count) {
        for (SZMethodInfo *m in info.classMethods) [out appendFormat:@"%@\n", m.declaration];
        [out appendString:@"\n"];
    }
    if (info.instanceMethods.count) {
        for (SZMethodInfo *m in info.instanceMethods) [out appendFormat:@"%@\n", m.declaration];
        [out appendString:@"\n"];
    }
    [out appendString:@"@end\n"];
    return out;
}

@end
